def load_config(path: str | Path = DEFAULT_CONFIG) -> dict:
    path = Path(path)
    config = json.loads(path.read_text(encoding="utf-8"))
    required = {"master_seed", "bootstrap_seed", "parameters", "monte_carlo", "crr", "hedging", "gamma_analysis", "sensitivity"}
    missing = required - set(config)
    if missing:
        raise ValueError(f"Study configuration is missing: {', '.join(sorted(missing))}")
    return config


def derive_seed(master_seed: int, label: str) -> int:
    """Derive a stable uint32 seed from a master seed and semantic label."""
    if isinstance(master_seed, bool) or not isinstance(master_seed, int) or master_seed < 0:
        raise ValueError("master_seed must be a non-negative integer")
    digest = hashlib.sha256(f"{master_seed}:{label}".encode("utf-8")).digest()
    return int.from_bytes(digest[:4], "little")


def write_csv(path: Path, rows: list[dict]) -> None:
    if not rows:
        raise ValueError(f"Cannot write an empty CSV: {path}")
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


def prepare_output(path: Path, *, replace: bool = False) -> Path:
    """Prepare an output directory without allowing destructive writes elsewhere."""
    path = path.resolve()
    protected = [ROOT / "src", ROOT / "paper", ROOT / "tests", ROOT / "config", ROOT / ".github"]
    if path == ROOT or any(path == item or item in path.parents for item in protected):
        raise ValueError("Refusing to replace a protected repository directory.")
    if path.exists() and any(path.iterdir()):
        if not replace:
            raise ValueError(f"Output directory is not empty: {path}. Use --force to replace it.")
        shutil.rmtree(path)
    path.mkdir(parents=True, exist_ok=True)
    return path


def _hedge_summary(result) -> dict:
    summary = result.summary()
    errors = result.errors
    return {
        **summary,
        "q05": float(np.quantile(errors, 0.05)),
        "median": float(np.quantile(errors, 0.50)),
        "q95": float(np.quantile(errors, 0.95)),
    }


def _manifest(output_dir: Path, scientific_files: list[Path]) -> dict:
    items = []
    for path in sorted(scientific_files):
        relative = path.relative_to(output_dir).as_posix()
        items.append({"path": relative, "sha256": hashlib.sha256(path.read_bytes()).hexdigest()})
    manifest = {
        "scope": "Exact SHA-256 provenance fingerprints for committed scientific outputs. Cross-machine verification uses tight numerical tolerances for CSV/JSON; environment metadata and PNG rendering are excluded.",
        "files": items,
    }
    (output_dir / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return manifest


